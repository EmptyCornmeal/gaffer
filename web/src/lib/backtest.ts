/**
 * True when a baseline beats Gaffer's `p_start` at every horizon on Brier.
 *
 * Derived rather than written into the page, for the same reason
 * `baselineSweeps` is: a hand-typed verdict outlives the artifact that made it
 * true, and this one is a verdict against ourselves.
 */
export function minutesBaselineSweeps(m: MinutesModel): boolean {
  const hs = Object.keys(m.per_horizon ?? {})
  if (!hs.length) return false
  return hs.every((h) => {
    const b = m.per_horizon![h].brier
    const ours = b.gaffer
    return Object.entries(b).some(([k, v]) => k !== 'gaffer' && v < ours)
  })
}

/** Horizons in the minutes block, numerically ordered. */
export function minutesHorizonKeys(m: MinutesModel): string[] {
  return Object.keys(m.per_horizon ?? {}).sort((a, b) => Number(a) - Number(b))
}

