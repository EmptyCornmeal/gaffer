// Backtest artifact schema + validation.
//
// The Accuracy page previously rendered a legacy artifact produced by a harness
// that scored a *substitute* model (it injected a different fixture multiplier
// and clean-sheet formula, and filtered the evaluation set on post-match
// minutes). Those numbers were published as if they described the shipped
// model. This module makes the schema explicit and refuses anything it does not
// recognise, so that cannot silently recur.

/**
 * Schema versions this build can render.
 *
 * 8 is the current one: it adds `minutes_model`, the first measurement of
 * `p_start` — the component that gates every other number on this page. Purely
 * additive, so a v7 artifact renders exactly as it did, minus that one section.
 *
 * 7 is kept alongside it deliberately, and this is a transition state rather
 * than a permanent pair. `backtest.json` is generated by hand (`python -m
 * gaffer.backtest --write`) and appears in no workflow, so between a deploy
 * carrying this code and someone regenerating the artifact the published file
 * is still v7; accepting only 8 would blank the Accuracy page for that window.
 * Drop 7 once the deployed artifact is v8.
 *
 * 6 was dropped when 8 arrived: keeping a three-wide window means the page can
 * render a measurement two splits old with nothing on it saying so.
 *
 * Supported rather than rejected because v7 is not *wrong*. Versions 3, 4 and 5
 * are refused below because rendering them would put a withdrawn or mislabelled
 * number back on the page. A v7 artifact is an honest measurement that is
 * missing a section — superseded, not retracted — and that distinction is the
 * entire reason the two lists exist separately.
 */
export const SUPPORTED_SCHEMA_VERSIONS = [7, 8] as const
/**
 * Versions we know about and deliberately refuse.
 *
 * 3 is refused: it reported `fpl_xp` and `ensemble` as measured baselines, and
 * those were computed from the archive's `xP` column, which is inadmissible.
 * Rendering a v3 artifact would put a withdrawn number back on the page.
 *
 * 4 is refused: it reported one collapsed model verdict, which said trained
 * models lost every decision metric. Ridge did not. A v4 artifact cannot show
 * the per-candidate evidence, so it would repeat the claim it got wrong.
 *
 * 5 is refused: it evaluated GW2 onwards while describing itself as covering
 * GW1, so its headline numbers are in-season numbers wearing an all-season
 * label — and it carries no `pre_season` block, so a build rendering it would
 * present the pre-season regime as measured when it never was.
 *
 * 6 is refused as of schema 8, and for a different reason from the four above
 * it: it is honest, but it reports 2024-25 under a page that now describes the
 * 2025-26 split, and it predates every minutes number. Two splits of drift is
 * further than a transition window should stretch.
 */
export const REJECTED_SCHEMA_VERSIONS = [1, 2, 3, 4, 5, 6] as const

